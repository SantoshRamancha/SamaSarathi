using Samasarathi.Application.Abstractions;

namespace Samasarathi.Infrastructure.Storage;

/// <summary>Saves files to a local folder. Swap for Azure Blob Storage in production.</summary>
public sealed class LocalFileStorage(string rootPath) : IFileStorage
{
    public async Task<string> SaveAsync(Stream content, string extension, CancellationToken ct = default)
    {
        Directory.CreateDirectory(rootPath);
        var key = $"{Guid.NewGuid():N}{extension.ToLowerInvariant()}";
        await using var file = File.Create(PathFor(key));
        await content.CopyToAsync(file, ct);
        return key;
    }

    public Task<Stream?> OpenReadAsync(string key, CancellationToken ct = default)
    {
        var path = PathFor(key);
        return Task.FromResult<Stream?>(File.Exists(path) ? File.OpenRead(path) : null);
    }

    public Task DeleteAsync(string key, CancellationToken ct = default)
    {
        File.Delete(PathFor(key));
        return Task.CompletedTask;
    }

    // Keys are generated by us; rejecting anything path-like stops "../" tricks.
    private string PathFor(string key) =>
        Path.GetFileName(key) == key ? Path.Combine(rootPath, key) : throw new ArgumentException("Invalid key.", nameof(key));
}
